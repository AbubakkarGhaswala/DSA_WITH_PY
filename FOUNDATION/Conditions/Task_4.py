# Hello Everyone And Welcome To day we are going to take 3 inputs from the user and check which number is greatest among them using conditions (if , elif , else)


num_1 = int(input("Enter Number 1 :- "))
num_2 = int(input("Enter Number 2 :- "))
num_3 = int(input("Enter Number 3 :- "))


if num_1 > num_2 and num_1 > num_3:
    print(f"{num_1} - Number 1 Is Greatest Among {num_1 , num_2 , num_3}")
elif num_2 > num_1 and num_2 > num_3:
    print(f"{num_2} - Number 2 Is Greatest Among {num_1 , num_2 , num_3}")
elif num_3 > num_1 and num_3 > num_2:
    print(f"{num_3} - Number 3 Is Greatest Among {num_1 , num_2 , num_3}")



