# Hello Everyone And Welcome To day we are going to check that is input number from user is positive or negative or zero using conditions (if , elif , else)


num = int(input("Enter Number For Check :- "))

if num > 0:
    print(f"{num} - This Number Is Positive!")
elif num < 0:
    print(f"{num} - This Number Is Negative!")
elif num == 0:
    print(f"{num} - This Number Is Zero!")



