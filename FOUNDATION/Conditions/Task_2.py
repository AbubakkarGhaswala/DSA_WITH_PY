# Hello Everyone And Welcome To day we are going to check that is input number from user is eligible for voting or not using conditions (if , elif , else)


age = int(input("Enter Your Age:- "))

if age >= 18:
    print("Yayyy! You’re Eligible For Voting")
elif age <= 0:
    print("Enter Valid Number!!")

elif age < 18:
    print("Ohh Noo ! You’re Not Eligible For Voting")


