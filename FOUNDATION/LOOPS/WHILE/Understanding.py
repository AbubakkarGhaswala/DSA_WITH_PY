# Hello Everyone to day we are going to learn about while loop in python 
# while loop is used to repeat a block of code as long as a condition is true 
# syntax of while loop is : 
# while condition : 
#     block of code 
# 
# example of while loop : 
# i = 1 
# while i <= 10 : 
#     print(i) 
#     i += 1 

# # in this example i is initialized to 1 
# # then the while loop checks if i is less than or equal to 10 
# # if it is true then it prints the value of i 
# # and then it increments the value of i by 1 
# # this process continues until the value of i is no longer less than or equal to 10 
